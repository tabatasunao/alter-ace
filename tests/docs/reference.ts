function classes(catalog: Catalog, out: string[]): void {
  const { allyMix, enemyMix, fillerClass } = catalog.armies;
  out.push('## Unit classes', '');
  out.push(
    'Each class carries exactly one unit weapon. Army share is the fraction of each army; the filler class takes',
    'whatever the other shares leave.',
    '',
  );
  table(
    out,
    ['Class', 'HP', 'Speed', 'Size', 'Weapon', 'Armor', 'Allied share', 'Enemy share', 'Traits'],
    'l---ll--l',
    catalog.classes.map((c) => [
      c.name,
      n(c.hp),
      n(c.speed),
      n(c.size),
      c.enemyWeapon ? `${catalog.unitWeapon(c.weapon).name} (enemy: ${catalog.unitWeapon(c.enemyWeapon).name})` : catalog.unitWeapon(c.weapon).name,
      catalog.armor(c.armor).name,
      share(c.id, allyMix, fillerClass),
      share(c.id, enemyMix, fillerClass),
      classTraits(c),
    ]),
  );
}

function classTraits(c: UnitClassDef): string {
  const s: string[] = [];
  if (c.semiAce) s.push('semi-ace');
  if (c.aceHitMul) s.push(`takes ${mul(c.aceHitMul)} from aces and semi-aces`);
  if (c.shield) s.push(`shield ${sec(c.shield.duration)} / ${sec(c.shield.cooldown)} recharge`);
  if (c.huntsAce) s.push('hunts the ace');
  if (c.nearAce) s.push(`stalks the ace within ${n(c.nearAce)}`);
  if (c.rally) s.push(`rallies ${c.rally.min}–${c.rally.max} units`);
  if (c.kiteDistance) s.push(`backs off inside ${n(c.kiteDistance)}`);
  if (c.aura) s.push(`aura: allies within ${n(c.aura.radius)} fire ${pct(c.aura.fireRateMul - 1)} faster`);
  if (c.heal) s.push(`heals its army within ${n(c.heal.radius)} by ${pct(c.heal.amount)} of max HP every ${sec(c.heal.interval)} (allied Healers: the ace too)`);
  return s.join('; ') || '–';
}

function share(id: string, mix: ArmyMix, filler: string): string {
  if (id === filler) return `rest (${pct(1 - Object.values(mix).reduce((a, b) => a + b, 0))})`;
  return mix[id] === undefined ? '–' : pct(mix[id]);
}

function unitWeapons(catalog: Catalog, out: string[]): void {
  const { unitVsUnit, aceDamageTaken } = catalog.battle.balance;
  out.push('## Unit weapons', '');
  out.push(
    `Damage is per hit before scaling: hits on other units are multiplied by ${n(unitVsUnit)} (\`unitVsUnit\`), hits on the`,
    `ace by ${n(aceDamageTaken)} (\`aceDamageTaken\`). Units close to about ${pct(catalog.battle.ai.approachFactor)} of their range.`,
    '',
  );
  table(
    out,
    ['Weapon', 'Behavior', 'Type', 'Damage', 'Range', 'Time between shots', 'Specials', 'Carried by'],
    'lll---ll',
    catalog.unitWeapons.map((w) => [
      w.name,
      `\`${w.behavior}\``,
      catalog.damageType(w.damageType).name,
      n(w.dmg),
      n(w.range),
      sec(w.interval),
      unitWeaponSpecials(w),
      [
        ...catalog.classes.filter((c) => c.weapon === w.id).map((c) => (c.enemyWeapon ? `${c.name} (allied)` : c.name)),
        ...catalog.classes.filter((c) => c.enemyWeapon === w.id).map((c) => `${c.name} (enemy)`),
      ].join(', ') || '–',
    ]),
  );
}

function unitWeaponSpecials(w: UnitWeaponDef): string {
  const s: string[] = [];
  switch (w.behavior) {
    case 'shot':
      s.push(w.projectile);
      if (w.pellets && w.pellets > 1) s.push(`${w.pellets} pellets`);
      if (w.pierce) s.push(`pierces ${w.pierce}`);
      if (w.splash) s.push(`splash ${n(w.splash)} for ${n(w.splashDmg ?? 0)}`);
      break;
    case 'missile':
      s.push(`salvo ${w.salvo}`, `splash ${n(w.splash)} for ${n(w.splashDmg)}`);
      if (w.launchAngle) s.push(`launches ${launchWord(w.launchAngle)}`);
      if (w.weave) s.push('weaving swarm');
      break;
    case 'lance':
      s.push(`charges ${sec(w.charge)}, aim locks for the last ${sec(w.lock)}`, `hits the whole line within ${n(w.width)}`);
      if (w.look === 'heavyBeam') s.push('drawn as a heavy beam');
      break;
    case 'saber':
      s.push(`lunge, slash ${n(w.slash)} reach over ${deg(w.arcHalfAngle * 2)}`);
      break;
  }
  return s.join('; ');
}

function armies(catalog: Catalog, out: string[]): void {
  const a = catalog.armies;
  const { min, max } = catalog.loadout.enemyCount;
  const sizes = [...new Set([min, catalog.loadout.defaultLoadout.enemies, max])];
  out.push('## Armies', '');
  out.push(
    `- **Allies:** ${a.battle.allies.count} units in ${a.battle.allies.groups} groups on the west side. No reinforcements.`,
    `- **Enemies:** ${min} to ${max} (picked in the hangar, steps of ${catalog.loadout.enemyCount.step}). Up to ${a.battle.enemies.initial} deploy in ${a.battle.enemies.groups} groups in the east.`,
    `- **Reinforcements:** the rest arrive from the east edge in battalions of ${a.reinforcements.battalion}, every ${sec(a.reinforcements.interval)} or sooner once fewer than ${a.reinforcements.fieldThreshold} enemies remain on the field.`,
    `- **Filler class:** ${catalog.unitClass(a.fillerClass).name} fills whatever the shares leave.`,
    `- **Minimums:** ${Object.entries(a.minimums).map(([id, k]) => `${k} ${catalog.unitClass(id).name}${k === 1 ? '' : 's'}`).join(', ') || 'none'} per army, whatever its size.`,
    '',
  );
  out.push('Unit counts per army (exact: counts are rounded shares, raised to the minimums; only the order is random):', '');
  const columns: { label: string; counts: Map<string, number> }[] = [
    { label: `Allies (${a.battle.allies.count})`, counts: countArmy(catalog, a.battle.allies.count, a.allyMix) },
    ...sizes.map((size) => ({ label: `Enemies (${size})`, counts: countArmy(catalog, size, a.enemyMix) })),
  ];
  table(
    out,
    ['Class', ...columns.map((c) => c.label)],
    `l${'-'.repeat(columns.length)}`,
    catalog.classes.map((c) => [c.name, ...columns.map((col) => String(col.counts.get(c.id) ?? 0))]),
  );
}

function countArmy(catalog: Catalog, size: number, mix: ArmyMix): Map<string, number> {
  const counts = new Map<string, number>();
  for (const id of armyList(size, mix, catalog.armies, new SeededRandom(1))) counts.set(id, (counts.get(id) ?? 0) + 1);
  return counts;
}

