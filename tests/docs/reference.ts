/** A Markdown table. `align` has one char per column: 'l' left, '-' right (numbers). */
function table(out: string[], headers: string[], align: string, rows: string[][]): void {
  out.push(`| ${headers.join(' | ')} |`);
  out.push(`|${headers.map((_, i) => (align[i] === 'l' ? ' --- |' : ' --: |')).join('')}`);
  for (const r of rows) out.push(`| ${r.map((c) => c.replace(/\|/g, '\\|')).join(' | ')} |`);
  out.push('');
}

/** A number without float noise: 0.30000000000000004 → "0.3". */
const n = (x: number): string => String(+x.toFixed(3));
const sec = (x: number): string => `${n(x)} s`;
const mul = (x: number): string => `×${n(x)}`;
const pct = (x: number): string => `${+(x * 100).toFixed(1)}%`;
const deg = (rad: number): string => `${Math.round((rad * 180) / Math.PI)}°`;
const launchWord = (rad: number): string => (Math.abs(rad - Math.PI) < 0.01 ? 'backwards' : rad === 0 ? 'forwards' : `at ${deg(rad)}`);
