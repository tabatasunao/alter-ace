/**
 * docs/reference.md: every number a player or designer asks about, rendered straight from the
 * Catalog (public/data/*.json). `npm run docs` writes it; tests/docs.test.ts fails when it is stale.
 * Keep this a pure function of the data: no simulation, no dates, so the output is stable.
 */
export function renderReference(catalog: Catalog): string {
  const out: string[] = [
    '# ALTER reference',
    '',
    '> Generated by `npm run docs` from `public/data/*.json`. Do not edit by hand: change the data, then',
    '> run `npm run docs`. `npm test` fails when this page no longer matches the data.',
    '',
    'Numbers are the raw data values. Distances are world units (the battlefield is',
    `${catalog.battle.world.width} × ${catalog.battle.world.height}), times are seconds. For what they mean in play, see`,
    '[mechanics.md](mechanics.md); for how to change them, see [data.md](data.md).',
    '',
    '- [Ace frames](#ace-frames)',
    '- [Ace weapons](#ace-weapons)',
    '- [Tools](#tools)',
    '- [Aim modes](#aim-modes)',
    '- [Damage types and armor](#damage-types-and-armor)',
    '- [Unit classes](#unit-classes)',
    '- [Unit weapons](#unit-weapons)',
    '- [Armies](#armies)',
    '- [Battle rules](#battle-rules)',
    '',
  ];
  frames(catalog, out);
  weapons(catalog, out);
  tools(catalog, out);
  aimModes(catalog, out);
  damage(catalog, out);
  classes(catalog, out);
  unitWeapons(catalog, out);
  armies(catalog, out);
  rules(catalog, out);
  return out.join('\n');
}

